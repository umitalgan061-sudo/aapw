assert.ok(audit.summary.score>=.9);
assert.equal(auditReleaseEvidenceV67(audit).p0,true);
const replay=buildEnvironmentRuntimeV67({samples,clock:12,dayOfYear:180,seed:'governance-v67'});
assert.equal(replay.digest,runtime.digest);
assert.deepEqual(replay.runtime.samples,runtime.runtime.samples);
assert.deepEqual(replay.hazards,runtime.hazards);
assert.deepEqual(replay.resources,runtime.resources);
assert.deepEqual(replay.interactions,runtime.interactions);
assert.deepEqual(replay.events.events,runtime.events.events);
assert.equal(replay.observability.health.rate,runtime.observability.health.rate);
