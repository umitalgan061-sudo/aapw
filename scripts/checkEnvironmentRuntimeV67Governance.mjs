const performance=performanceSummaryV67(samples,'desktop');
const ledger={evaluations:V67_SCENARIOS.map(s=>({id:s.id,hash:s.id,runtime}))};
const gate=buildReleaseGateV67(runtime,{platform:'desktop',admitted:10,total:28});
