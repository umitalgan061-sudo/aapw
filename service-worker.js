// ── ACTIVATE ──
self.addEventListener('activate', (event) => {
    const KEEP = [MEDIA_CACHE, SHELL_CACHE];
    event.waitUntil(
        caches.keys().then(keys => {
            return Promise.all(
                keys.filter(key => !KEEP.includes(key))
                    .map(key => {
                        return caches.delete(key);
                    })
            );
        }).then(() => self.clients.claim())
    );
});

